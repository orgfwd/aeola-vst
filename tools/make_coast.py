import json, math

def dp(pts, tol):
    # iterative Douglas-Peucker on (lon, lat) degrees (good enough at this tolerance)
    n = len(pts)
    if n < 3: return pts
    keep = [False] * n; keep[0] = keep[-1] = True
    stack = [(0, n - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = pts[a]; bx, by = pts[b]
        dx, dy = bx - ax, by - ay
        L = math.hypot(dx, dy)
        best, bi = -1.0, -1
        for i in range(a + 1, b):
            px, py = pts[i]
            d = abs(dy * (px - ax) - dx * (py - ay)) / L if L > 1e-12 else math.hypot(px - ax, py - ay)
            if d > best: best, bi = d, i
        if best > tol:
            keep[bi] = True; stack.append((a, bi)); stack.append((bi, b))
    return [p for p, k in zip(pts, keep) if k]

gj = json.load(open("ne_10m_coastline.geojson"))
out = []; total = 0; nlines = 0
for f in gj["features"]:
    g = f["geometry"]
    lines = g["coordinates"] if g["type"] == "MultiLineString" else [g["coordinates"]]
    for l in lines:
        pts = [(p[0], p[1]) for p in l]
        s = dp(pts, 0.012)
        q = []
        for lon, lat in s:                      # 0.01 degree grid (~1.1 km), drop repeats
            t = (int(round(lat * 100)), int(round(lon * 100)))
            if not q or q[-1] != t: q.append(t)
        if len(q) < 2: continue
        # polylines longer than 30000 points are split (int16 count)
        out.append(len(q)); 
        for la, lo in q: out.extend([la, lo])
        total += len(q); nlines += 1
out.append(0)
print("lines", nlines, "points", total, "ints", len(out))
with open("Source/Coast.h", "w") as f:
    f.write("// Aeola - world coastline for the map's land layer.\n// Source: Natural Earth 1:10m coastline (public domain, naturalearthdata.com), simplified (Douglas-Peucker, 0.012 deg) and stored\n// on a 0.01 degree grid. Layout: repeated [pointCount, lat*100, lon*100, ...], terminated by a 0 count. Generated by tools/make_coast.py.\n#pragma once\n#include <cstdint>\nnamespace aeola\n{\nstatic const int16_t kCoastData[] = {\n")
    line = []
    for v in out:
        line.append(str(v))
        if len(line) >= 24:
            f.write(",".join(line) + ",\n"); line = []
    if line: f.write(",".join(line) + "\n")
    f.write("};\nstatic const int kCoastDataCount = %d;\n}\n" % len(out))
